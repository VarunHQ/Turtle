import turtle



turtle.title("A simple square using Python Turtle Library!")

turtle.Screen().bgcolor("lightblue")

board = turtle.Turtle()


screen = turtle.Screen()
screen.setup(400, 300)


board.forward(100)
board.left(90)

board.forward(100)
board.left(90)

board.forward(100)
board.left(90)
board.forward(100)

turtle.done() 